const assert = require('node:assert/strict');
const fs = require('node:fs');
const {JSDOM} = require('jsdom');
const dom = new JSDOM(`<body>${fs.readFileSync('src/styler/templates/sample-viewer.html', 'utf8')}<wa-tab-panel id="active"></wa-tab-panel><wa-tab-panel hidden><button data-style-viewer><img src="/hidden.png"></button></wa-tab-panel></body>`, {runScripts:'outside-only', url:'http://example.test'});
const {window} = dom;
const centered = [];
window.HTMLElement.prototype.scrollIntoView = function(options) { centered.push({element:this, options}); };
const panel = window.document.getElementById('active');
function add(name) {
    const button = window.document.createElement('button');
    button.dataset.styleViewer = '';
    button.setAttribute('aria-label', name);
    button.innerHTML = `<img src="/${name}.png" alt="${name}">`;
    panel.append(button);
    return button;
}
const first = add('first');
add('second');
window.eval(fs.readFileSync('src/artifact_editor/static/js/styler-image-viewer.js', 'utf8'));
first.querySelector('img').click();
const dialog = window.document.getElementById('styler-image-viewer');
const image = window.document.getElementById('styler-image-full');
const previous = window.document.getElementById('styler-image-previous');
const next = window.document.getElementById('styler-image-next');
assert.equal(dialog.open, true);
assert.equal(image.src, 'http://example.test/first.png');
assert.equal(previous.disabled, true);
next.click();
assert.equal(image.src, 'http://example.test/second.png');
assert.equal(next.disabled, true, 'Hidden categories must not enter the gallery');
add('newly-completed');
window.document.dispatchEvent(new window.KeyboardEvent('keydown', {key:'ArrowRight'}));
assert.equal(image.src, 'http://example.test/newly-completed.png');
window.document.dispatchEvent(new window.KeyboardEvent('keydown', {key:'ArrowLeft'}));
assert.equal(image.src, 'http://example.test/second.png');
const progress = window.document.getElementById('styler-viewer-progress');
function status(state, style_tag='van_gogh') {
    window.document.dispatchEvent(new window.CustomEvent('styler:sample-status', {detail:{state, style_tag, style_name:'Vincent van Gogh', engine:'qwen', percent:45, message:'Sampling'}}));
}
status('running');
assert.equal(progress.hidden, false);
assert.match(progress.textContent, /Vincent van Gogh — Qwen Image 2.1: Sampling \(45%\)/);
assert.equal(window.document.getElementById('styler-viewer-progress-bar').getAttribute('value'), '45');
status('complete', 'another_style');
assert.equal(progress.hidden, false);
status('complete');
assert.equal(progress.hidden, true);
const completed = add('websocket-completed');
completed.dispatchEvent(new window.CustomEvent('styler:sample-complete', {bubbles:true}));
assert.equal(image.src, 'http://example.test/websocket-completed.png');
assert.equal(dialog.label, 'websocket-completed');
assert.equal(centered.at(-1).element, completed);
assert.equal(centered.at(-1).options.block, 'center');
assert.equal(next.disabled, true);
previous.click();
assert.equal(image.src, 'http://example.test/newly-completed.png');
dialog.open = false;
dialog.dispatchEvent(new window.Event('wa-after-hide'));
assert.equal(centered.at(-1).element.querySelector('img').alt, 'newly-completed');
const scrollCount = centered.length;
const closedCompletion = add('closed-completion');
closedCompletion.dispatchEvent(new window.CustomEvent('styler:sample-complete', {bubbles:true}));
assert.equal(dialog.open, false);
assert.equal(centered.length, scrollCount, 'Closed viewer must not scroll for completions');
assert.equal(image.src, 'http://example.test/newly-completed.png');
window.document.dispatchEvent(new window.KeyboardEvent('keydown', {key:'ArrowLeft'}));
assert.equal(image.src, 'http://example.test/newly-completed.png');
dom.window.close();
console.log('Styler image viewer navigation passed');
