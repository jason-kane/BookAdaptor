const assert = require('node:assert/strict');
const fs = require('node:fs');
const {JSDOM} = require('jsdom');
(async () => {
    const dom = new JSDOM('<wa-tab-group id="category-tab-group"><wa-tab panel="tag_custom" data-style-category="custom"></wa-tab><wa-tab panel="tag_art & ink" data-style-category="art &amp; ink"></wa-tab></wa-tab-group>', {url:'http://example.test/styles/#art%20%26%20ink',runScripts:'outside-only'});
    const {window} = dom;
    for (const name of ['wa-tab-group','wa-tab','wa-tab-panel','wa-slider']) window.customElements.define(name,class extends window.HTMLElement {});
    const requests=[];
    let processed = false;
    window.htmx={process:element=>{if (element.id==='category-tab-group') processed=true; else assert.equal(element.tagName,'WA-TAB');},trigger:(tab,event)=>{assert.ok(processed,'Install HTMX handlers before requesting content');requests.push([tab.dataset.styleCategory,event]);}};
    window.eval(fs.readFileSync('src/artifact_editor/static/js/styler-categories.js','utf8'));
    await new Promise(resolve=>setImmediate(resolve));
    const group=window.document.getElementById('category-tab-group');
    assert.equal(group.active,'tag_art & ink');
    assert.deepEqual(requests,[['art & ink','styler-category-load']]);
    group.active='tag_custom';group.dispatchEvent(new window.Event('wa-tab-show'));
    assert.equal(window.location.pathname+window.location.hash,'/styles/#custom');
    assert.equal(requests.length,2);
    group.dispatchEvent(new window.Event('wa-tab-show'));
    assert.equal(requests.length,2,'Duplicate selection must not reload a category');
    window.history.replaceState(null,'','/styles/#art%20%26%20ink');
    window.dispatchEvent(new window.HashChangeEvent('hashchange'));
    assert.equal(group.active,'tag_art & ink');
    assert.equal(requests.length,3);
    window.history.replaceState(null,'','/styles/#%bad');
    window.dispatchEvent(new window.HashChangeEvent('hashchange'));
    assert.equal(requests.length,3,'Malformed hashes must be ignored');
    window.document.dispatchEvent(new window.CustomEvent('styler:category-empty',{detail:{tag:'art & ink'}}));
    assert.equal(group.active,'tag_custom','Last tab falls back to previous neighbor');
    assert.equal(window.location.hash,'#custom');
    assert.equal(group.querySelectorAll('wa-tab').length,1);
    const extra=window.document.createElement('wa-tab');
    extra.dataset.styleCategory='next';extra.setAttribute('panel','tag_next');group.append(extra);
    window.document.dispatchEvent(new window.CustomEvent('styler:category-empty',{detail:{tag:'custom'}}));
    assert.equal(group.active,'tag_next','Prefer the next neighbor');
    assert.equal(window.location.hash,'#next');
    assert.equal(requests.at(-1)[0],'next','Load the new category content');
    window.document.dispatchEvent(new window.CustomEvent('styler:category-empty',{detail:{tag:'next'}}));
    assert.equal(group.querySelectorAll('wa-tab').length,0);
    assert.equal(window.location.hash,'');
    window.document.dispatchEvent(new window.CustomEvent('styler:category-added',{detail:{tag:'stock only',count:0,stockpile_count:3}}));
    const stockTab = group.querySelector('[data-style-category="stock only"]');
    assert.equal(stockTab.textContent, 'stock only (3)');
    window.document.dispatchEvent(new window.CustomEvent('styler:category-empty',{detail:{tag:'stock only'}}));
    assert.ok(stockTab.isConnected, 'Stockpile-only tags must remain available');
    window.document.dispatchEvent(new window.CustomEvent('styler:category-added',{detail:{tag:'stock only',count:2}}));
    assert.equal(stockTab.textContent, 'stock only (5)');
    window.fetch = async () => ({ok:true,json:async()=>({categories:[{tag:'stock only',count:2,stockpile_count:4},{tag:'new stock tag',count:0,stockpile_count:1}]})});
    window.document.body.dispatchEvent(new window.CustomEvent('stockpile-refresh'));
    await new Promise(resolve=>setImmediate(resolve));
    assert.equal(stockTab.textContent, 'stock only (6)');
    assert.equal(group.querySelector('[data-style-category="new stock tag"]').textContent, 'new stock tag (1)');
    window.fetch = async () => ({ok:true,json:async()=>({categories:[]})});
    window.document.body.dispatchEvent(new window.CustomEvent('stockpile-refresh'));
    await new Promise(resolve=>setImmediate(resolve));
    assert.equal(stockTab.textContent, 'stock only (2)', 'Removing stockpile membership preserves style membership');
    assert.equal(group.querySelector('[data-style-category="new stock tag"]'), null);
    dom.window.close();
    console.log('Styler category URL selection passed');
})();
