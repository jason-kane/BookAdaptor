"""OAuth for the local editor's shared YouTube upload account."""
import hmac
import json
import os
from pathlib import Path
import tempfile
import time

from flask import Blueprint, current_app, redirect, request

SCOPES = ["https://www.googleapis.com/auth/youtube.upload"]
bp = Blueprint("youtube_oauth", __name__)
COOKIE = "youtube_oauth_state"


def directory():
    path = Path(current_app.config.get("YOUTUBE_OAUTH_DIR") or os.environ.get(
        "YOUTUBE_OAUTH_DIR", str(Path(__file__).resolve().parents[3] / ".youtube-oauth")))
    path.mkdir(mode=0o700, parents=True, exist_ok=True)
    return path


def save_private(path, data):
    fd, temporary = tempfile.mkstemp(dir=path.parent)
    try:
        with os.fdopen(fd, "w") as stream:
            json.dump(data, stream)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def make_flow(**kwargs):
    from google_auth_oauthlib.flow import Flow
    return Flow.from_client_secrets_file(
        str(directory() / "client_secret.json"), scopes=SCOPES,
        redirect_uri=current_app.config.get("YOUTUBE_REDIRECT_URI") or os.environ.get(
            "YOUTUBE_REDIRECT_URI", "http://localhost:8080/oauth/youtube/callback"),
        **kwargs,
    )


def connected():
    try:
        data = json.loads((directory() / "credentials.json").read_text())
        return bool(data.get("refresh_token"))
    except (OSError, ValueError):
        return False


def get_youtube_client():
    from google.oauth2.credentials import Credentials
    from google.auth.transport.requests import Request
    from googleapiclient.discovery import build
    path = directory() / "credentials.json"
    credentials = Credentials.from_authorized_user_file(str(path), SCOPES)
    if credentials.expired and credentials.refresh_token:
        credentials.refresh(Request())
        save_private(path, json.loads(credentials.to_json()))
    return build("youtube", "v3", credentials=credentials)


def start_connection(return_url):
    try:
        flow = make_flow(autogenerate_code_verifier=True)
        from urllib.parse import urlsplit
        if urlsplit(flow.redirect_uri).netloc != request.host:
            return "Open the editor at the configured YouTube callback origin before connecting.", 400
        authorization_url, state = flow.authorization_url(
            access_type="offline", prompt="consent", include_granted_scopes="true")
        save_private(directory() / (state + ".pending"), {
            "created": time.time(), "return_url": return_url,
            "code_verifier": flow.code_verifier,
        })
    except (OSError, ValueError, ImportError):
        return "YouTube OAuth is not configured. Check the server's client_secret.json and Google OAuth dependencies.", 503
    response = redirect(authorization_url)
    response.set_cookie(COOKIE, state, max_age=600, httponly=True,
                        secure=request.is_secure, samesite="Lax", path="/oauth/youtube/callback")
    return response


@bp.get("/oauth/youtube/callback")
def callback():
    state = request.args.get("state", "")
    cookie = request.cookies.get(COOKIE, "")
    if not state or not cookie or not hmac.compare_digest(state, cookie):
        return "YouTube connection expired or invalid. Start again from the YouTube tab.", 400
    # State is also a filename: accept only the URL-safe characters generated by OAuthlib.
    if not all(c.isascii() and (c.isalnum() or c in "-_") for c in state):
        return "Invalid OAuth state.", 400
    pending = directory() / (state + ".pending")
    try:
        data = json.loads(pending.read_text())
        pending.unlink()  # Each authorization attempt can be used only once.
        if time.time() - data["created"] > 600:
            raise ValueError("Expired authorization")
    except (OSError, ValueError, KeyError):
        return "YouTube connection expired. Start again from the YouTube tab.", 400
    result = "denied" if request.args.get("error") else "failed"
    if request.args.get("code") and not request.args.get("error"):
        try:
            flow = make_flow(state=state, code_verifier=data["code_verifier"])
            flow.fetch_token(code=request.args["code"])
            credentials = flow.credentials
            if not credentials.refresh_token or not credentials.has_scopes(SCOPES):
                raise ValueError("Upload permission and offline access are required")
            save_private(directory() / "credentials.json", json.loads(credentials.to_json()))
            result = "connected"
        except Exception as error:
            # OAuth exceptions may contain codes or tokens; don't expose their contents.
            error_type = type(error).__name__
            # Store only the exception class and known OAuth error identifiers.
            # Exception messages and response bodies may contain credentials.
            known_errors = {'invalid_client', 'invalid_grant', 'access_denied',
                            'invalid_scope', 'unauthorized_client'}
            oauth_error = getattr(error, 'error', None)
            diagnostic = {'type': error_type,
                          'oauth_error': oauth_error if oauth_error in known_errors else None}
            current_app.logger.warning("YouTube OAuth token exchange failed (%s, %s)",
                                       diagnostic['type'], diagnostic['oauth_error'])
            try:
                save_private(directory() / 'last_error.json', diagnostic)
            except OSError:
                pass
    response = redirect(data["return_url"] + "?youtube_connection=" + result)
    response.delete_cookie(COOKIE, path="/oauth/youtube/callback")
    return response
